#!/usr/bin/env python3
"""Build content.js for the IGCSE English course site.

Reads the markdown in ../course/ (and ../README.md for the overview) and emits a
single content.js holding every section as pre-rendered HTML. The site is fully
static: no runtime markdown parsing, no CDN, no build step needed to serve it.

Re-run after editing the markdown:

    cd docs && python3 build.py
"""
import json
import os
import re

import markdown

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# (id, path relative to repo root, nav label, group)
SECTIONS = [
    ("overview",   "README.md",                              "Overview",                   "Start"),
    ("module-01",  "course/01-diagnostic-test.md",           "01 · Diagnostic Test",       "Modules"),
    ("module-02",  "course/02-foundations-grammar-punctuation.md", "02 · Grammar & Punctuation", "Modules"),
    ("module-03",  "course/03-vocabulary-and-expression.md", "03 · Vocabulary",            "Modules"),
    ("module-04",  "course/04-reading-comprehension.md",     "04 · Reading",               "Modules"),
    ("module-05",  "course/05-summary-skills.md",            "05 · Summary Skills",        "Modules"),
    ("module-06",  "course/06-directed-writing.md",          "06 · Directed Writing",      "Modules"),
    ("module-07",  "course/07-composition-descriptive-narrative.md", "07 · Composition",   "Modules"),
    ("module-08",  "course/08-language-analysis-r4.md",      "08 · Language Analysis",     "Modules"),
    ("module-09",  "course/09-practice-paper.md",            "09 · Mock Paper",            "Modules"),
    ("answer-key", "course/10-answer-key.md",                "Answer Key",                 "Reference"),
    ("progress",   "course/progress.md",                     "Progress Sheet",             "Reference"),
]

EXTENSIONS = ["tables", "fenced_code", "sane_lists", "attr_list", "md_in_html"]


def first_heading(text, fallback):
    m = re.search(r"^#\s+(.+)$", text, re.M)
    return m.group(1).strip() if m else fallback


def build():
    out = []
    for sid, rel, label, group in SECTIONS:
        with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
            raw = f.read()
        # The leading H1 becomes the page title, so drop it from the body.
        body = re.sub(r"^#\s+.+\n", "", raw, count=1)
        html = markdown.markdown(body, extensions=EXTENSIONS)
        out.append({
            "id": sid,
            "label": label,
            "title": first_heading(raw, label),
            "group": group,
            "html": html,
        })
    payload = json.dumps({"sections": out}, ensure_ascii=False, separators=(",", ":"))
    js = "/* Generated by build.py — do not edit by hand. */\nwindow.COURSE = " + payload + ";\n"
    dest = os.path.join(HERE, "content.js")
    with open(dest, "w", encoding="utf-8") as f:
        f.write(js)
    print("wrote %s (%s bytes, %d sections)" % (dest, format(len(js), ","), len(out)))


if __name__ == "__main__":
    build()
