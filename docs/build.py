#!/usr/bin/env python3
"""Build content.js for the IGCSE English course site.

Reads the markdown in ../course/ (and ../README.md for the overview) and emits a
single content.js holding every section as pre-rendered HTML. The site is fully
static: no runtime markdown parsing, no CDN, no build step needed to serve it.

Re-run after editing the markdown:

    cd docs && python3 build.py
"""
import json
import os
import re

import markdown

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# (id, path relative to repo root, nav label, group, emoji, blurb)
SECTIONS = [
    ("overview", "README.md", "Overview", "Start", "\U0001F680",
     "What this course is, the two IGCSE routes, and the 8-week plan."),
    ("dashboard", None, "My Progress", "Start", "\U0001F4C8",
     "Your quiz scores, completed sections and answers - saved in this browser."),
    ("module-01", "course/01-diagnostic-test.md", "Diagnostic Test", "Modules", "\U0001FA7A",
     "A 45-minute placement test that finds your level and your top errors."),
    ("module-02", "course/02-foundations-grammar-punctuation.md", "Grammar & Punctuation", "Modules", "\u270F\uFE0F",
     "Tense, agreement, speech marks and commas - the marks you must not lose."),
    ("module-03", "course/03-vocabulary-and-expression.md", "Vocabulary", "Modules", "\U0001F4AC",
     "Swap weak words for precise ones and make your writing come alive."),
    ("module-04", "course/04-reading-comprehension.md", "Reading", "Modules", "\U0001F4D6",
     "Answer the question that was actually asked, and back every point with the text."),
    ("module-05", "course/05-summary-skills.md", "Summary Skills", "Modules", "\U0001F4DD",
     "The most teachable question on the paper - there is a method, and it wins marks."),
    ("module-06", "course/06-directed-writing.md", "Directed Writing", "Modules", "\u2709\uFE0F",
     "Letters, articles, speeches and reports - matching your words to your reader."),
    ("module-07", "course/07-composition-descriptive-narrative.md", "Composition", "Modules", "\U0001F3A8",
     "Descriptive and narrative writing: plan it, pace it, land the ending."),
    ("module-08", "course/08-language-analysis-r4.md", "Language Analysis", "Modules", "\U0001F50D",
     "How writers create effects - say what the words do to the reader."),
    ("module-09", "course/09-practice-paper.md", "Mock Paper", "Modules", "\u23F1\uFE0F",
     "A full timed paper, sat under exam conditions."),
    ("answer-key", "course/10-answer-key.md", "Answer Key", "Reference", "\u2705",
     "Every answer, model answer and band descriptor."),
    ("progress", "course/progress.md", "Progress Sheet", "Reference", "\U0001F4CA",
     "Your score sheet and Top 5 Errors list."),
]

EXTENSIONS = ["tables", "fenced_code", "sane_lists", "attr_list", "md_in_html"]

GROUP_EMOJI = {"Start": "\U0001F3C1", "Modules": "\U0001F4DA", "Reference": "\U0001F5C2\uFE0F"}


def first_heading(text, fallback):
    m = re.search(r"^#\s+(.+)$", text, re.M)
    return m.group(1).strip() if m else fallback


def build():
    quiz_path = os.path.join(ROOT, "course", "quizzes.json")
    quizzes = {}
    if os.path.exists(quiz_path):
        with open(quiz_path, encoding="utf-8") as f:
            quizzes = {k: v for k, v in json.load(f).items() if not k.startswith("_")}

    out = []
    for sid, rel, label, group, emoji, blurb in SECTIONS:
        if rel is None:
            raw, html, kind = "", "", "dashboard"
        else:
            with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
                raw = f.read()
            # The leading H1 becomes the page title, so drop it from the body.
            body = re.sub(r"^#\s+.+\n", "", raw, count=1)
            html, kind = markdown.markdown(body, extensions=EXTENSIONS), "doc"
        out.append({
            "id": sid,
            "label": label,
            "title": first_heading(raw, label),
            "group": group,
            "groupEmoji": GROUP_EMOJI.get(group, "\u2022"),
            "emoji": emoji,
            "blurb": blurb,
            "kind": kind,
            "quiz": quizzes.get(sid),
            "html": html,
        })
    payload = json.dumps({"sections": out}, ensure_ascii=False, separators=(",", ":"))
    js = "/* Generated by build.py - do not edit by hand. */\nwindow.COURSE = " + payload + ";\n"
    dest = os.path.join(HERE, "content.js")
    with open(dest, "w", encoding="utf-8") as f:
        f.write(js)
    print("wrote %s (%s bytes, %d sections)" % (dest, format(len(js), ","), len(out)))


if __name__ == "__main__":
    build()
